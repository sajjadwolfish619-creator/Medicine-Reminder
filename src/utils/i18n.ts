export function getWeekdayName(day: Weekday, lang: Language, short = false): string {
  const key = short ? `${day}Short` : day;
  // @ts-expect-error dynamic access
  return translations[lang][key] || day;
}

export function getCategoryLabel(category: MedicationCategory, lang: Language): string {
  const key = `cat_${category}` as keyof typeof translations['en'];
  return translations[lang][key] || category;
}

export function getIconLabel(icon: MedicationIconType, lang: Language): string {
  const key = `icon_${icon}` as keyof typeof translations['en'];
  return translations[lang][key] || icon;
}

export function getMealTimingLabel(timing: MealTiming, lang: Language): string {
  return translations[lang][timing] || timing;
}
